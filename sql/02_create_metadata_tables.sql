-- ========================================================
-- OpsLens Schema & Metadata Tables DDL
-- Exathon 2026 Track 04
-- ========================================================

CREATE SCHEMA IF NOT EXISTS OPSLENS;
OPEN SCHEMA OPSLENS;

-- 0. Configuration & Reference Clock Table
CREATE TABLE IF NOT EXISTS OPSLENS.CONFIG (
    PARAM_KEY VARCHAR(64) PRIMARY KEY,
    PARAM_VALUE VARCHAR(256) NOT NULL,
    DESCRIPTION VARCHAR(500),
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 1. Pipeline Jobs Definition Table
CREATE TABLE IF NOT EXISTS OPSLENS.PIPELINE_JOBS (
    JOB_ID VARCHAR(64) PRIMARY KEY,
    JOB_NAME VARCHAR(128) NOT NULL,
    SCHEDULE VARCHAR(64) NOT NULL,
    EXPECTED_RUNTIME_SEC DECIMAL(9,2) NOT NULL,
    SOURCE_SYSTEM VARCHAR(64) NOT NULL,
    TARGET_TABLE VARCHAR(64) NOT NULL,
    DESCRIPTION VARCHAR(500),
    IS_ACTIVE BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Pipeline Execution Run Log (60-day history with 5 stages per job: extract, load, validate, transform, publish)
CREATE TABLE IF NOT EXISTS OPSLENS.PIPELINE_RUN_LOG (
    RUN_ID VARCHAR(64) PRIMARY KEY,
    BATCH_ID VARCHAR(64) NOT NULL,
    JOB_ID VARCHAR(64) NOT NULL,
    STAGE VARCHAR(32) NOT NULL,
    START_TIME TIMESTAMP NOT NULL,
    END_TIME TIMESTAMP NOT NULL,
    DURATION_SEC DECIMAL(9,2) NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    ROWS_LOADED DECIMAL(18,0) DEFAULT 0,
    ERROR_MESSAGE VARCHAR(2000),
    IS_SIMULATED BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. Data Lineage Edges (Sources -> Jobs -> Tables -> Marts -> Dashboards)
CREATE TABLE IF NOT EXISTS OPSLENS.LINEAGE_EDGES (
    EDGE_ID VARCHAR(64) PRIMARY KEY,
    SOURCE_NODE_ID VARCHAR(64) NOT NULL,
    SOURCE_NODE_TYPE VARCHAR(32) NOT NULL,
    SOURCE_LABEL VARCHAR(128) NOT NULL,
    TARGET_NODE_ID VARCHAR(64) NOT NULL,
    TARGET_NODE_TYPE VARCHAR(32) NOT NULL,
    TARGET_LABEL VARCHAR(128) NOT NULL,
    RELATION_TYPE VARCHAR(32) NOT NULL
);

-- 4. Check Results (Data Quality & Sanity Validations - Populated ONLY by Sentinel)
CREATE TABLE IF NOT EXISTS OPSLENS.CHECK_RESULTS (
    CHECK_ID VARCHAR(64) PRIMARY KEY,
    CHECK_NAME VARCHAR(128) NOT NULL,
    TABLE_NAME VARCHAR(64) NOT NULL,
    CHECK_TYPE VARCHAR(64) NOT NULL,
    SEVERITY VARCHAR(16) NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    EXPECTED_VALUE VARCHAR(256),
    ACTUAL_VALUE VARCHAR(256),
    MESSAGE VARCHAR(1000),
    EXECUTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    IS_SIMULATED BOOLEAN DEFAULT TRUE
);

-- 5. Observability Alerts Table (Populated ONLY by Sentinel)
CREATE TABLE IF NOT EXISTS OPSLENS.ALERTS (
    ALERT_ID VARCHAR(64) PRIMARY KEY,
    INCIDENT_TYPE VARCHAR(64) NOT NULL,
    SEVERITY VARCHAR(16) NOT NULL,
    TARGET_OBJECT VARCHAR(128) NOT NULL,
    SUMMARY VARCHAR(500) NOT NULL,
    DETAILS VARCHAR(2000),
    SUGGESTED_ROOT_CAUSE VARCHAR(1000),
    RECOMMENDED_ACTION VARCHAR(1000),
    STATUS VARCHAR(32) NOT NULL,
    FIRST_SEEN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    LAST_SEEN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    RESOLVED_AT TIMESTAMP,
    IS_SIMULATED BOOLEAN DEFAULT TRUE
);

-- 6. Table & Pipeline Trust Scores (Populated ONLY by Trust Engine)
CREATE TABLE IF NOT EXISTS OPSLENS.TRUST_SCORES (
    SCORE_ID VARCHAR(64) PRIMARY KEY,
    OBJECT_NAME VARCHAR(128) NOT NULL,
    OBJECT_TYPE VARCHAR(32) NOT NULL,
    TRUST_SCORE DECIMAL(5,2) NOT NULL,
    FRESHNESS_SCORE DECIMAL(5,2) NOT NULL,
    COMPLETENESS_SCORE DECIMAL(5,2) NOT NULL,
    UNIQUENESS_SCORE DECIMAL(5,2) NOT NULL,
    CONSISTENCY_SCORE DECIMAL(5,2) NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    COMPUTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    IS_SIMULATED BOOLEAN DEFAULT TRUE
);

-- 7. Metric Baselines for Anomaly Detection
CREATE TABLE IF NOT EXISTS OPSLENS.BASELINES (
    BASELINE_ID VARCHAR(64) PRIMARY KEY,
    OBJECT_NAME VARCHAR(128) NOT NULL,
    METRIC_NAME VARCHAR(64) NOT NULL,
    BASELINE_MEAN DOUBLE PRECISION NOT NULL,
    BASELINE_STDDEV DOUBLE PRECISION NOT NULL,
    MIN_THRESHOLD DOUBLE PRECISION NOT NULL,
    MAX_THRESHOLD DOUBLE PRECISION NOT NULL,
    WINDOW_DAYS DECIMAL(9,0) DEFAULT 14,
    EXTRA_METADATA VARCHAR(4000),
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    IS_SIMULATED BOOLEAN DEFAULT TRUE
);

-- 8. Query Workload Telemetry for Cost Radar
CREATE TABLE IF NOT EXISTS OPSLENS.QUERY_STATS (
    QUERY_ID VARCHAR(64) PRIMARY KEY,
    USER_NAME VARCHAR(64) NOT NULL,
    TEAM VARCHAR(32) NOT NULL,
    QUERY_HASH VARCHAR(64) NOT NULL,
    QUERY_TEXT VARCHAR(2000) NOT NULL,
    TARGET_TABLES VARCHAR(500),
    START_TIME TIMESTAMP NOT NULL,
    DURATION_SEC DOUBLE PRECISION NOT NULL,
    CPU_SECONDS DOUBLE PRECISION NOT NULL,
    RAM_PEAK_MB DOUBLE PRECISION NOT NULL,
    ROWS_RETURNED DECIMAL(18,0) DEFAULT 0,
    ESTIMATED_COST_USD DOUBLE PRECISION NOT NULL,
    EXECUTION_MODE VARCHAR(32) DEFAULT 'DIRECT',
    IS_SIMULATED BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 9. Fault Injection Audit Log
CREATE TABLE IF NOT EXISTS OPSLENS.FAULT_LOG (
    FAULT_ID VARCHAR(64) PRIMARY KEY,
    FAULT_NAME VARCHAR(64) NOT NULL,
    TARGET_TABLE VARCHAR(64) NOT NULL,
    DETAILS VARCHAR(1000) NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    INJECTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CLEARED_AT TIMESTAMP
);
