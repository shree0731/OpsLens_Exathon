-- ========================================================
-- OpsLens Baselines Queries
-- Computes rolling statistics, runtime medians, and schema metadata
-- ========================================================

-- 1. Daily Row Count History per Job / Table (last 14 days)
SELECT 
    JOB_ID,
    STAGE,
    AVG(ROWS_LOADED) AS AVG_ROWS,
    STDDEV(ROWS_LOADED) AS STDDEV_ROWS,
    COUNT(*) AS SAMPLE_COUNT
FROM OPSLENS.PIPELINE_RUN_LOG
WHERE STAGE IN ('load', 'transform', 'publish')
  AND START_TIME >= CURRENT_TIMESTAMP - INTERVAL '14' DAY
GROUP BY JOB_ID, STAGE;

-- 2. Stage Duration Medians and Standard Deviations per Job and Stage
SELECT 
    JOB_ID,
    STAGE,
    MEDIAN(DURATION_SEC) AS MEDIAN_DURATION,
    AVG(DURATION_SEC) AS AVG_DURATION,
    STDDEV(DURATION_SEC) AS STDDEV_DURATION,
    MIN(DURATION_SEC) AS MIN_DURATION,
    MAX(DURATION_SEC) AS MAX_DURATION,
    COUNT(*) AS SAMPLE_COUNT
FROM OPSLENS.PIPELINE_RUN_LOG
WHERE START_TIME >= CURRENT_TIMESTAMP - INTERVAL '14' DAY
  AND STATUS = 'SUCCESS'
GROUP BY JOB_ID, STAGE
ORDER BY JOB_ID, STAGE;

-- 3. Production Table Schema Column Snapshot
SELECT 
    COLUMN_TABLE,
    COLUMN_ORDINAL_POSITION,
    COLUMN_NAME,
    COLUMN_TYPE,
    COLUMN_IS_NULLABLE
FROM SYS.EXA_ALL_COLUMNS
WHERE COLUMN_SCHEMA = 'OPSLENS'
  AND COLUMN_TABLE IN ('ORDERS', 'LINEITEM', 'CUSTOMER', 'ENERGY_READINGS', 'ENERGY_METERS', 'WEATHER_DAILY')
ORDER BY COLUMN_TABLE, COLUMN_ORDINAL_POSITION;

-- 4. Per-Order Price Reconciliation Baseline Query
SELECT 
    COUNT(*) AS TOTAL_ORDERS,
    SUM(CASE WHEN ABS(O.O_TOTALPRICE - L.CALC_TOTAL) > 0.10 THEN 1 ELSE 0 END) AS MISMATCHED_ORDERS,
    ROUND(SUM(CASE WHEN ABS(O.O_TOTALPRICE - L.CALC_TOTAL) > 0.10 THEN 1 ELSE 0 END) / COUNT(*), 6) AS MISMATCH_RATIO,
    ROUND(SUM(ABS(O.O_TOTALPRICE - L.CALC_TOTAL)), 2) AS TOTAL_ABS_DELTA
FROM OPSLENS.ORDERS O
JOIN (
    SELECT 
        L_ORDERKEY, 
        ROUND(SUM(L_EXTENDEDPRICE * (1 - L_DISCOUNT) * (1 + L_TAX)), 2) AS CALC_TOTAL
    FROM OPSLENS.LINEITEM
    GROUP BY L_ORDERKEY
) L ON O.O_ORDERKEY = L.L_ORDERKEY;
